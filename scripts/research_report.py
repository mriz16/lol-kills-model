"""Player research checks -> reports/player_research.md.

1. Do boom / bust types carry over? Last 150 days vs the 150 days before: Spearman
   correlation of each measure per role, and how often a player gets the same type again
   (33% by chance).
The recent-form check (does the player's last-20 average beat the model?) is in
scripts/form_report.py (reports/backtest_form.md).

    python -m scripts.research_report --data data_branch
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from src.app import research as R
from scripts.run_backtest import _md as _table
from src.config import DATA_DIR, REPORTS_DIR


def _md(df: pd.DataFrame) -> str:
    return _table(df, 2)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=DATA_DIR)
    ap.add_argument("--out", type=Path, default=REPORTS_DIR / "player_research.md")
    args = ap.parse_args(argv)
    players = pd.read_parquet(args.data / "players.parquet")
    end = pd.Timestamp(players["date"].max())
    L = ["# Player research checks", "",
         f"Data through {end:%Y-%m-%d}. Generated by `scripts/research_report.py`.", "",
         "## 1. Do boom / bust types carry over?", "",
         f"Per-map kills, last {R.ARCHETYPE_DAYS} days vs the {R.ARCHETYPE_DAYS} days "
         f"before, players with >= {R.ARCHETYPE_MIN_MAPS} maps in both. vmr = variance / "
         "mean (spread for the same average). Type = top / middle / bottom third of vmr "
         "in the role (33% same type again by chance).", ""]
    pers = R.persistence(players)
    L += [f"{pers['n']} players.", "", "Spearman correlation, this window vs the previous:",
          "", _md(pers["corr"].round(2).reset_index()), "",
          "Same type again (rows: previous type):", "",
          _md(pers["same_type"].round(2).reset_index()), ""]
    out = args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
