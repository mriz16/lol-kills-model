"""Player research checks -> reports/player_research.md.

1. Do boom / bust types carry over? Last 150 days vs the 150 days before: Spearman
   correlation of each measure per role, and how often a player gets the same type again
   (33% by chance).
2. Recent form vs the model (needs backtest rows, `run_backtest.py --rows-only`): the
   player's last-20 average of the same market before each series minus the model mean,
   against actual minus model mean. Slope > 0 = the model under-reacts to recent form.
3. Who decides a line: over rate at the rounded-median line by the team's series result.

    python -m scripts.research_report --data data_branch --rows reports/backtest_rows_proj.parquet
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from src.app import research as R
from scripts.run_backtest import _md as _table
from src.config import DATA_DIR, REPORTS_DIR


def _md(df: pd.DataFrame) -> str:
    return _table(df, 2)


def recent_form(rows: pd.DataFrame, players: pd.DataFrame, n_last: int = 20,
                min_prev: int = 10) -> pd.DataFrame:
    """rows + avg_prev (mean of the player's previous n_last series of the market) and
    gap = avg_prev - model mean; rows with < min_prev previous series dropped."""
    out = []
    for (pl, mk), g in rows.groupby(["player", "market"]):
        t = R.market_totals(players, pl, mk).sort_values("date")
        td, tk = t["date"].values, t["kills"].values
        for i, d in zip(g.index, g["date"].values):
            j = np.searchsorted(td, d, side="left")
            prev = tk[:j][-n_last:]
            out.append((i, len(prev), prev.mean() if len(prev) else np.nan))
    o = pd.DataFrame(out, columns=["i", "n_prev", "avg_prev"]).set_index("i")
    r = rows.join(o)
    r = r[r["n_prev"] >= min_prev].copy()
    r["gap"] = r["avg_prev"] - r["mean"]
    r["err"] = r["y"] - r["mean"]
    return r


def slope_se(r: pd.DataFrame, n_boot: int = 200, seed: int = 0) -> tuple[float, float]:
    """OLS slope of err on gap and its series-clustered bootstrap se."""
    b = float(np.polyfit(r["gap"], r["err"], 1)[0])
    rng = np.random.default_rng(seed)
    ids = r["series_id"].unique()
    by = r.set_index("series_id")
    bs = []
    for _ in range(n_boot):
        x = by.loc[rng.choice(ids, len(ids))]
        bs.append(np.polyfit(x["gap"], x["err"], 1)[0])
    return b, float(np.std(bs))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=DATA_DIR)
    ap.add_argument("--rows", type=Path, help="backtest rows parquet (recent-form check)")
    ap.add_argument("--variants", nargs="*", default=None)
    ap.add_argument("--out", type=Path, default=REPORTS_DIR / "player_research.md")
    args = ap.parse_args(argv)
    players = pd.read_parquet(args.data / "players.parquet")
    end = pd.Timestamp(players["date"].max())
    L = ["# Player research checks", "",
         f"Data through {end:%Y-%m-%d}. Generated by `scripts/research_report.py`.", "",
         "## 1. Do boom / bust types carry over?", "",
         f"Per-map kills, last {R.ARCHETYPE_DAYS} days vs the {R.ARCHETYPE_DAYS} days "
         f"before, players with >= {R.ARCHETYPE_MIN_MAPS} maps in both. vmr = variance / "
         "mean (spread for the same average). Type = top / middle / bottom third of vmr "
         "in the role (33% same type again by chance).", ""]
    pers = R.persistence(players)
    L += [f"{pers['n']} players.", "", "Spearman correlation, this window vs the previous:",
          "", _md(pers["corr"].round(2).reset_index()), "",
          "Same type again (rows: previous type):", "",
          _md(pers["same_type"].round(2).reset_index()), ""]
    if args.rows and args.rows.exists():
        rows = pd.read_parquet(args.rows)
        variants = args.variants or sorted(rows["variant"].unique())
        L += ["## 2. Recent form vs the model", "",
              "gap = the player's average over the previous 20 series of the same market "
              "minus the model mean; err = actual minus model mean. A slope of 0 means "
              "recent form adds nothing to the model.", "",
              "| variant | rows | slope | se |", "|---|---|---|---|"]
        for v in variants:
            r = recent_form(rows[rows["variant"] == v].copy(), players)
            b, se = slope_se(r)
            L.append(f"| {v} | {len(r)} | {b:.3f} | {se:.3f} |")
        r = recent_form(rows[rows["variant"] == variants[0]].copy(), players)
        r["gap bin"] = pd.qcut(r["gap"], 5)
        t = r.groupby(["market", "gap bin"], observed=True).agg(
            n=("err", "size"), gap=("gap", "mean"), err=("err", "mean")).round(2)
        L += ["", f"By gap quintile ({variants[0]}):", "", _md(t.reset_index()), ""]
    out = args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
